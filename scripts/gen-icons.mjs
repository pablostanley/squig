function pathsOf(name, weight) {
  // non-regular weights carry the weight suffix in the file name
  const file = join(assetsRoot, weight, weight === "regular" ? `${name}.svg` : `${name}-${weight}.svg`)
  if (!existsSync(file)) return null
  const svg = readFileSync(file, "utf8")
  const ds = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1])
  return ds.length ? ds : null
}

function pathMap(names, weight) {
  const out = {}
  const missing = []
  for (const name of names) {
    const ds = pathsOf(name, weight)
    if (ds) out[name] = ds
    else missing.push(name)
  }
  return { out, missing }
}

function pathMapBody(map) {
  return Object.entries(map)
    .map(([k, v]) => `  ${JSON.stringify(k)}: [${v.map((d) => JSON.stringify(d)).join(", ")}],`)
    .join("\n")
}

// -- curated inline subset (regular) ----------------------------------------

const curated = pathMap([...new Set(CURATED)], "regular")
writeFileSync(
  join(root, "lib/sketch/phosphor-paths.ts"),
  `${GENERATED}\n` +
    `// Phosphor "regular" icons — the curated subset the main bundle carries so\n` +
    `// library defs render with no flash. The full catalog lives in ./phosphor/.\n\n` +
    `export const PHOSPHOR_VB = 256\n\n` +
    `export const PHOSPHOR_PATHS: Record<string, string[]> = {\n${pathMapBody(curated.out)}\n}\n`
)
console.log(`phosphor-paths.ts: ${Object.keys(curated.out).length} curated icons`)
if (curated.missing.length) console.log(`  curated missing (skipped): ${curated.missing.join(" ")}`)

// -- full catalog ------------------------------------------------------------

const genDir = join(root, "lib/sketch/phosphor")
mkdirSync(genDir, { recursive: true })

const allNames = CATALOG.map((i) => i.name).sort()

for (const weight of WEIGHTS) {
  const { out, missing } = pathMap(allNames, weight)
  writeFileSync(
    join(genDir, `catalog-${weight}.ts`),
    `${GENERATED}\n` +
      `// Every Phosphor "${weight}" icon, filled paths in a 0 0 256 256 viewBox.\n` +
      `// Loaded lazily via lib/sketch/icon-catalog.ts — never import directly.\n\n` +
      `export const PATHS: Record<string, string[]> = {\n${pathMapBody(out)}\n}\n`
  )
  console.log(`phosphor/catalog-${weight}.ts: ${Object.keys(out).length} icons`)
  if (missing.length) console.log(`  ${weight} missing (skipped): ${missing.join(" ")}`)
}

// -- eager name list ---------------------------------------------------------

writeFileSync(
  join(genDir, "names.ts"),
  `${GENERATED}\n` +
    `// Every Phosphor icon name — eager and small, so "unknown icon" and\n` +
    `// "still loading" can be told apart synchronously.\n\n` +
    `export const ALL_ICON_NAMES: string[] = ${JSON.stringify(allNames)}\n`
)
console.log(`phosphor/names.ts: ${allNames.length} names`)

// -- lazy search index -------------------------------------------------------

const meta = CATALOG.map((i) => [
  i.name,
  i.tags.filter((t) => t !== "*new*" && t !== "*updated*").join(" "),
  i.categories.join(" "),
])
writeFileSync(
  join(genDir, "meta.ts"),
  `${GENERATED}\n` +
    `// Search index: [name, tags, categories] per icon. Loaded lazily by\n` +
    `// lib/sketch/icon-search.ts alongside the first icon search.\n\n` +
    `export const ICON_META: [string, string, string][] = ${JSON.stringify(meta)}\n`
)
console.log(`phosphor/meta.ts: ${meta.length} entries`)
