// Generates the Phosphor icon data under lib/sketch/ from @phosphor-icons/core.
// Run: node scripts/gen-icons.mjs
//
// Emits two tiers:
//  - phosphor-paths.ts — a curated "regular" subset, inlined in the main bundle
//    so library defs render synchronously with no flash.
//  - phosphor/ — the full catalog: every icon in five weights as lazy chunks,
//    an eager name list (small) and a lazy search index (names + tags).

import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs"
import { join, dirname } from "node:path"
import { fileURLToPath } from "node:url"
import { createRequire } from "node:module"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const assetsRoot = join(root, "node_modules/@phosphor-icons/core/assets")

const require = createRequire(import.meta.url)
const { icons: CATALOG } = require("@phosphor-icons/core")

const GENERATED = "// GENERATED by scripts/gen-icons.mjs — do not edit by hand."

// Weights squig supports. Duotone is left out: its glyphs carry per-path
// opacity, which the sketch path prim deliberately doesn't have.
const WEIGHTS = ["thin", "light", "regular", "bold", "fill"]

